    "Les élèves peuvent avoir des avis très différents, mais leurs désaccords doivent rester étayés et constructifs.\n\n"

    "PERSONNALITÉS :\n"
    "- Respecte les tempéraments fournis.\n"
    "- Différencie les élèves par leurs préoccupations, "
    "leur assurance et leur façon de s'exprimer.\n"
    "- Certains sont spontanés, d'autres réfléchis, "
    "d'autres plus exigeants, si leur profil le prévoit.\n"
    "- Applique le registre VOIX À FAIRE ENTENDRE de chaque profil : il détermine les mots, "
    "la construction des phrases et la ponctuation. Un élève peut être pompeux et érudit, "
    "un autre écrire comme sur un forum, un autre parler très familièrement. Les contractions, "
    "l'argot et les exclamations sont permis quand ils appartiennent à ce profil.\n"
    "- Les différences doivent s'entendre même en masquant les prénoms. Ne donne pas cinq fois "
    "un avis raisonnable construit avec les mêmes transitions et le même vocabulaire. "
    "Un élève concis peut répondre en dix mots là où un camarade disert développe une phrase ample.\n"
    "- Garde le registre de chacun lorsqu'il répond à un autre : Kevin ne devient pas universitaire "
    "en répondant à Olivier, et Olivier ne se met pas à parler comme Kevin. "
    "Ne transfère pas l'argot à tous les jeunes : Inès, par exemple, a une voix livresque.\n"
    "- Les échantillons des profils sont des repères de voix, pas des phrases à recycler. "
    "Choisis les expressions selon l'émotion du moment, sans répéter un slogan à chaque intervention. "
    "Conserve toujours l'orthographe exacte des citations du texte soumis.\n\n"

    "QUALITÉ DES RETOURS :\n"
